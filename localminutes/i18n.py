class LanguageManager:
    """Dictionary-based runtime bilingual (EN / TR) localization helper."""

    def __init__(self, lang: str = DEFAULT_LANGUAGE) -> None:
        self._lang = lang if lang in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE

    @property
    def lang(self) -> str:
        return self._lang

    def set_language(self, lang: str) -> None:
        if lang in SUPPORTED_LANGUAGES:
            self._lang = lang

    def t(self, key: str, **kwargs: object) -> str:
        table = TRANSLATIONS.get(self._lang, TRANSLATIONS[DEFAULT_LANGUAGE])
        template = table.get(key) or TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
        if kwargs:
            try:
                return template.format(**kwargs)
            except Exception:
                return template
        return template
